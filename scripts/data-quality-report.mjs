import { mkdir, writeFile } from 'node:fs/promises';
import { validateFile, normalizeQuestion } from './validate-data.mjs';

function escapeCell(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function groupBy(records, keyFn) {
  const groups = new Map();
  for (const record of records) {
    const key = keyFn(record);
    if (!key) continue;
    const group = groups.get(key) ?? [];
    group.push(record);
    groups.set(key, group);
  }
  return [...groups.values()].filter((group) => group.length > 1);
}

function answerSignature(value) {
  return String(value ?? '')
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[\s、。！？!?「」『』（）()・:：;；,，.〜～約]/g, '');
}

export function buildQualityReport(result) {
  const exactGroups = groupBy(result.records, (record) => record.q.trim());
  const normalizedGroups = groupBy(result.records, (record) => normalizeQuestion(record.q));
  const conflictGroups = normalizedGroups.filter((group) => {
    const answers = new Set(group.map((record) => answerSignature(record.a)));
    return answers.size > 1;
  });

  const categoryCounts = new Map();
  for (const record of result.records) {
    categoryCounts.set(record.tag, (categoryCounts.get(record.tag) ?? 0) + 1);
  }

  const lines = [
    '# M3Quiz data-quality report',
    '',
    '> Generated by `npm run report:data`. Do not edit manually.',
    '',
    `- Questions: **${result.records.length}**`,
    `- Validation errors: **${result.errors.length}**`,
    `- Validation warnings: **${result.warnings.length}**`,
    `- Exact duplicate groups: **${exactGroups.length}**`,
    `- Normalized duplicate groups: **${normalizedGroups.length}**`,
    `- Potential answer-conflict groups: **${conflictGroups.length}**`,
    '',
    '## Category counts',
    '',
    '| Category | Questions |',
    '| --- | ---: |',
    ...[...categoryCounts.entries()]
      .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], 'ja'))
      .map(([tag, count]) => `| ${escapeCell(tag)} | ${count} |`),
    '',
    '## Potential answer conflicts',
    '',
  ];

  if (conflictGroups.length === 0) {
    lines.push('No normalized duplicate questions with different answers were found.');
  } else {
    for (const [index, group] of conflictGroups.entries()) {
      lines.push(`### Conflict ${index + 1}`, '');
      lines.push('| ID | Question | Answer |', '| ---: | --- | --- |');
      for (const record of group) {
        lines.push(`| ${escapeCell(record.id)} | ${escapeCell(record.q)} | ${escapeCell(record.a)} |`);
      }
      lines.push('');
    }
  }

  lines.push('## Exact duplicate groups', '');
  if (exactGroups.length === 0) {
    lines.push('No exact duplicate questions were found.');
  } else {
    for (const group of exactGroups) {
      lines.push(`- IDs ${group.map((record) => record.id).join(', ')}: ${escapeCell(group[0].q)}`);
    }
  }

  lines.push('', '## Validation messages', '');
  if (result.errors.length === 0 && result.warnings.length === 0) {
    lines.push('No validation messages.');
  } else {
    for (const error of result.errors) lines.push(`- **Error:** ${escapeCell(error)}`);
    for (const warning of result.warnings) lines.push(`- Warning: ${escapeCell(warning)}`);
  }

  return `${lines.join('\n')}\n`;
}

async function main() {
  const result = await validateFile(new URL('../questions.csv', import.meta.url));
  const output = buildQualityReport(result);
  const outputDirectory = new URL('../reports/', import.meta.url);
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(new URL('data-quality.md', outputDirectory), output, 'utf8');
  console.log(`Wrote reports/data-quality.md for ${result.records.length} questions.`);
  if (result.errors.length > 0) process.exitCode = 1;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
